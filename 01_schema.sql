  CONSTRAINT fk_placed_tower_type FOREIGN KEY (tower_type_id) REFERENCES tower_types(tower_type_id),
  CONSTRAINT fk_placed_build_point FOREIGN KEY (build_point_id) REFERENCES build_points(build_point_id),
  CONSTRAINT uq_placed_tower_cell UNIQUE (session_id, build_point_id),
