CREATE TABLE active_zombies (
  active_zombie_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  wave_progress_id     NUMBER NOT NULL,
  zombie_type_id       NUMBER NOT NULL,
  current_health       NUMBER(8) NOT NULL,
  max_health           NUMBER(8) DEFAULT 0 NOT NULL,
  armor_multiplier     NUMBER(6,2) DEFAULT 1 NOT NULL,
  route_point_id       NUMBER NOT NULL,
  segment_progress     NUMBER(8,4) DEFAULT 0 NOT NULL,
  status               VARCHAR2(20) DEFAULT 'active' NOT NULL,
  slow_until           NUMBER(10,2) DEFAULT 0 NOT NULL,
  speed_multiplier     NUMBER(4,2) DEFAULT 1 NOT NULL,
  CONSTRAINT pk_active_zombies PRIMARY KEY (active_zombie_id),
  CONSTRAINT fk_active_progress FOREIGN KEY (wave_progress_id) REFERENCES wave_progress(wave_progress_id) ON DELETE CASCADE,
  CONSTRAINT fk_active_zombie_type FOREIGN KEY (zombie_type_id) REFERENCES zombie_types(zombie_type_id),
  CONSTRAINT fk_active_route_point FOREIGN KEY (route_point_id) REFERENCES map_route(route_point_id),
  CONSTRAINT ck_active_status CHECK (status IN ('active', 'inactive')),
  CONSTRAINT ck_active_health CHECK (current_health >= 0 AND max_health >= 0 AND armor_multiplier >= 1),
  CONSTRAINT ck_active_progress CHECK (segment_progress >= 0 AND segment_progress < 1),
  CONSTRAINT ck_active_slow CHECK (slow_until >= 0 AND speed_multiplier > 0 AND speed_multiplier <= 1)
);

CREATE INDEX ix_active_zombies_progress ON active_zombies(wave_progress_id, status);

CREATE TABLE game_results (
  result_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  session_id       NUMBER NOT NULL,
  player_id        NUMBER NOT NULL,
  player_name      VARCHAR2(100 CHAR) NOT NULL,
  map_id           NUMBER NOT NULL,
  result_status    VARCHAR2(10) NOT NULL,
  reached_wave     NUMBER(4) NOT NULL,
  duration         NUMBER(10,2) NOT NULL,
  finished_at      DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_game_results PRIMARY KEY (result_id),
  CONSTRAINT uq_result_session UNIQUE (session_id),
  CONSTRAINT fk_result_session FOREIGN KEY (session_id) REFERENCES game_sessions(session_id),
  CONSTRAINT fk_result_player FOREIGN KEY (player_id) REFERENCES players(player_id),
  CONSTRAINT fk_result_map FOREIGN KEY (map_id) REFERENCES maps(map_id),
  CONSTRAINT ck_result_status CHECK (result_status IN ('win', 'lose')),
  CONSTRAINT ck_result_values CHECK (reached_wave > 0 AND duration >= 0)
);

CREATE OR REPLACE VIEW v_leaderboard AS
SELECT
  r.map_id,
  m.map_name,
  r.player_name,
  r.result_status,
  r.reached_wave,
  r.duration,
  r.finished_at,
  ROW_NUMBER() OVER (
    PARTITION BY r.map_id
    ORDER BY
      CASE r.result_status WHEN 'win' THEN 0 ELSE 1 END,
      r.reached_wave DESC,
      r.duration ASC,
      r.finished_at DESC
  ) AS place_no
FROM game_results r
JOIN maps m ON m.map_id = r.map_id;

