CREATE TABLE players (
  player_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  player_name     VARCHAR2(100 CHAR) NOT NULL,
  password_hash   VARCHAR2(255) NOT NULL,
  registered_at   DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_players PRIMARY KEY (player_id),
  CONSTRAINT uq_players_name UNIQUE (player_name),
  CONSTRAINT ck_players_name_not_blank CHECK (TRIM(player_name) IS NOT NULL)
);

CREATE TABLE trick_or_treat_actions (
  action_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  player_id         NUMBER NOT NULL,
  target_player_id  NUMBER NOT NULL,
  action_type       VARCHAR2(20) NOT NULL,
  backfired         NUMBER(1) DEFAULT 0 NOT NULL,
  created_at        DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_treat_actions PRIMARY KEY (action_id),
  CONSTRAINT fk_treat_player FOREIGN KEY (player_id) REFERENCES players(player_id),
  CONSTRAINT fk_treat_target FOREIGN KEY (target_player_id) REFERENCES players(player_id),
  CONSTRAINT ck_treat_action CHECK (action_type IN ('SWEET', 'TRICK')),
  CONSTRAINT ck_treat_backfire CHECK (backfired IN (0, 1))
);

CREATE UNIQUE INDEX uq_treat_daily ON trick_or_treat_actions(player_id, action_type, TRUNC(created_at));

CREATE TABLE player_effects (
  effect_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  action_id         NUMBER NOT NULL,
  source_player_id  NUMBER NOT NULL,
  target_player_id  NUMBER NOT NULL,
  effect_type       VARCHAR2(30) NOT NULL,
  effect_value      NUMBER(8,2) NOT NULL,
  starts_at         DATE DEFAULT SYSDATE NOT NULL,
  expires_at        DATE NOT NULL,
  is_backfire       NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT pk_player_effects PRIMARY KEY (effect_id),
  CONSTRAINT fk_effect_action FOREIGN KEY (action_id) REFERENCES trick_or_treat_actions(action_id) ON DELETE CASCADE,
  CONSTRAINT fk_effect_source FOREIGN KEY (source_player_id) REFERENCES players(player_id),
  CONSTRAINT fk_effect_target FOREIGN KEY (target_player_id) REFERENCES players(player_id),
  CONSTRAINT ck_effect_type CHECK (effect_type IN ('MONEY_BONUS', 'ZOMBIE_SPEED')),
  CONSTRAINT ck_effect_value CHECK (effect_value > 0),
  CONSTRAINT ck_effect_period CHECK (expires_at > starts_at),
  CONSTRAINT ck_effect_backfire CHECK (is_backfire IN (0, 1))
);

CREATE INDEX ix_player_effects_active ON player_effects(target_player_id, expires_at, effect_type);

CREATE TABLE maps (
  map_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  map_name           VARCHAR2(100 CHAR) NOT NULL,
  map_width          NUMBER(4) NOT NULL,
  map_height         NUMBER(4) NOT NULL,
  start_money        NUMBER(8) NOT NULL,
  start_base_health  NUMBER(8) NOT NULL,
  difficulty         VARCHAR2(20) DEFAULT 'normal' NOT NULL,
  CONSTRAINT pk_maps PRIMARY KEY (map_id),
  CONSTRAINT uq_maps_name UNIQUE (map_name),
  CONSTRAINT ck_maps_size CHECK (map_width > 0 AND map_height > 0),
  CONSTRAINT ck_maps_start_values CHECK (start_money >= 0 AND start_base_health > 0)
);

CREATE TABLE map_route (
  route_point_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  map_id          NUMBER NOT NULL,
  point_order     NUMBER(6) NOT NULL,
  x               NUMBER(4) NOT NULL,
  y               NUMBER(4) NOT NULL,
  CONSTRAINT pk_map_route PRIMARY KEY (route_point_id),
  CONSTRAINT fk_route_map FOREIGN KEY (map_id) REFERENCES maps(map_id) ON DELETE CASCADE,
  CONSTRAINT uq_route_order UNIQUE (map_id, point_order),
  CONSTRAINT uq_route_cell UNIQUE (map_id, x, y)
);

CREATE TABLE build_points (
  build_point_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  map_id          NUMBER NOT NULL,
  x               NUMBER(4) NOT NULL,
  y               NUMBER(4) NOT NULL,
  CONSTRAINT pk_build_points PRIMARY KEY (build_point_id),
  CONSTRAINT fk_build_map FOREIGN KEY (map_id) REFERENCES maps(map_id) ON DELETE CASCADE,
  CONSTRAINT uq_build_cell UNIQUE (map_id, x, y)
);

CREATE TABLE zombie_types (
  zombie_type_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  zombie_type_name  VARCHAR2(100 CHAR) NOT NULL,
  base_health       NUMBER(8) NOT NULL,
  base_speed        NUMBER(6,2) NOT NULL,
  armor             NUMBER(8) DEFAULT 0 NOT NULL,
  reward            NUMBER(8) NOT NULL,
  CONSTRAINT pk_zombie_types PRIMARY KEY (zombie_type_id),
  CONSTRAINT uq_zombie_type_name UNIQUE (zombie_type_name),
  CONSTRAINT ck_zombie_stats CHECK (base_health > 0 AND base_speed > 0 AND armor >= 0 AND reward >= 0)
);

CREATE TABLE tower_types (
  tower_type_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  tower_code     VARCHAR2(20) NOT NULL,
  tower_name     VARCHAR2(100 CHAR) NOT NULL,
  level_no       NUMBER(1) NOT NULL,
  damage         NUMBER(8) NOT NULL,
  range_cells    NUMBER(8) NOT NULL,
  fire_rate      NUMBER(6,2) NOT NULL,
  cost           NUMBER(8) NOT NULL,
  splash_radius  NUMBER(8) DEFAULT 0 NOT NULL,
  slow_percent   NUMBER(5,2) DEFAULT 0 NOT NULL,
  slow_duration  NUMBER(6,2) DEFAULT 0 NOT NULL,
  CONSTRAINT pk_tower_types PRIMARY KEY (tower_type_id),
  CONSTRAINT uq_tower_name UNIQUE (tower_name),
  CONSTRAINT uq_tower_level UNIQUE (tower_code, level_no),
  CONSTRAINT ck_tower_level CHECK (level_no BETWEEN 1 AND 3),
  CONSTRAINT ck_tower_stats CHECK (
    damage > 0
    AND range_cells > 0
    AND fire_rate > 0
    AND cost >= 0
    AND splash_radius >= 0
    AND slow_percent >= 0
    AND slow_percent < 1
    AND slow_duration >= 0
  )
);

CREATE TABLE waves (
  wave_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  map_id       NUMBER NOT NULL,
  wave_number  NUMBER(4) NOT NULL,
  CONSTRAINT pk_waves PRIMARY KEY (wave_id),
  CONSTRAINT fk_waves_map FOREIGN KEY (map_id) REFERENCES maps(map_id) ON DELETE CASCADE,
  CONSTRAINT uq_wave_number UNIQUE (map_id, wave_number),
  CONSTRAINT ck_wave_number CHECK (wave_number > 0)
);

CREATE TABLE wave_composition (
  wave_item_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  wave_id             NUMBER NOT NULL,
  zombie_type_id      NUMBER NOT NULL,
  zombie_count        NUMBER(6) NOT NULL,
  spawn_interval      NUMBER(6,2) NOT NULL,
  initial_delay       NUMBER(6,2) DEFAULT 0 NOT NULL,
  CONSTRAINT pk_wave_composition PRIMARY KEY (wave_item_id),
  CONSTRAINT fk_wave_item_wave FOREIGN KEY (wave_id) REFERENCES waves(wave_id) ON DELETE CASCADE,
  CONSTRAINT fk_wave_item_zombie FOREIGN KEY (zombie_type_id) REFERENCES zombie_types(zombie_type_id),
  CONSTRAINT ck_wave_item_values CHECK (zombie_count > 0 AND spawn_interval > 0 AND initial_delay >= 0)
);

CREATE TABLE game_sessions (
  session_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  player_id        NUMBER NOT NULL,
  player_name      VARCHAR2(100 CHAR) NOT NULL,
  map_id           NUMBER NOT NULL,
  money            NUMBER(8) NOT NULL,
  base_health      NUMBER(8) NOT NULL,
  current_wave     NUMBER(4) DEFAULT 1 NOT NULL,
  killed_zombies   NUMBER(8) DEFAULT 0 NOT NULL,
  simulation_time  NUMBER(10,2) DEFAULT 0 NOT NULL,
  status           VARCHAR2(20) DEFAULT 'running' NOT NULL,
  created_at       DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT pk_game_sessions PRIMARY KEY (session_id),
  CONSTRAINT fk_session_player FOREIGN KEY (player_id) REFERENCES players(player_id),
  CONSTRAINT fk_session_map FOREIGN KEY (map_id) REFERENCES maps(map_id),
  CONSTRAINT ck_session_money CHECK (money >= 0),
  CONSTRAINT ck_session_health CHECK (base_health >= 0),
  CONSTRAINT ck_session_kills CHECK (killed_zombies >= 0),
  CONSTRAINT ck_session_status CHECK (status IN ('running', 'win', 'lose'))
);

CREATE INDEX ix_sessions_player_status ON game_sessions(player_id, status);

CREATE TABLE wave_progress (
  wave_progress_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  session_id        NUMBER NOT NULL,
  wave_id           NUMBER NOT NULL,
  wave_item_id      NUMBER NOT NULL,
  released_count    NUMBER(6) DEFAULT 0 NOT NULL,
  next_spawn_time   NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_wave_progress PRIMARY KEY (wave_progress_id),
  CONSTRAINT fk_progress_session FOREIGN KEY (session_id) REFERENCES game_sessions(session_id) ON DELETE CASCADE,
  CONSTRAINT fk_progress_wave FOREIGN KEY (wave_id) REFERENCES waves(wave_id),
  CONSTRAINT fk_progress_wave_item FOREIGN KEY (wave_item_id) REFERENCES wave_composition(wave_item_id),
  CONSTRAINT uq_progress_item UNIQUE (session_id, wave_item_id),
  CONSTRAINT ck_progress_values CHECK (released_count >= 0 AND next_spawn_time >= 0)
);

CREATE TABLE placed_towers (
  placed_tower_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  session_id           NUMBER NOT NULL,
  tower_type_id        NUMBER NOT NULL,
  remaining_cooldown   NUMBER(8,2) DEFAULT 0 NOT NULL,
